# Text pools and constants used by bot handlers.

from collections.abc import Iterable


def _extend_unique(base: list[str], additions: Iterable[str], target_count: int) -> list[str]:
    phrases = list(dict.fromkeys(base))
    for phrase in additions:
        if phrase not in phrases:
            phrases.append(phrase)
        if len(phrases) == target_count:
            return phrases

    raise RuntimeError(f"Not enough phrases to build a pool of {target_count}.")


def _build_grid(
    starts: list[str],
    middles: list[str],
    endings: list[str],
) -> Iterable[str]:
    return (
        f"{start} {middle} {ending}"
        for start in starts
        for middle in middles
        for ending in endings
    )


